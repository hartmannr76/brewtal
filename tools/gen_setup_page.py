#!/usr/bin/env python3
"""
Embeds the device's web pages into the firmware:

    lib/network/web/setup.html       ->  lib/network/src/setup_page.cpp        (kSetupPage, kSetupPageLen)
    lib/network/web/brewfather.html  ->  lib/network/src/brewfather_page.cpp   (kBrewfatherPage, ...Len)

    python tools/gen_setup_page.py           regenerate
    python tools/gen_setup_page.py --check   exit 1 if a generated file is out of date
                                             (tools/check_rules.py runs this on every build)

Each generated file records its page's SHA-256, so a stale copy is caught without comparing bytes.
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(ROOT, "lib", "network", "web")
SRC_DIR = os.path.join(ROOT, "lib", "network", "src")
MARK = "// source sha256: "
# (page, generated file, symbol)
PAGES = [
    ("setup.html", "setup_page.cpp", "kSetupPage"),
    ("brewfather.html", "brewfather_page.cpp", "kBrewfatherPage"),
]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read_src(page):
    """The page with LF line endings, whatever the checkout uses (Windows may give CRLF)."""
    with open(os.path.join(WEB, page), "rb") as f:
        return f.read().replace(b"\r\n", b"\n")


def render(page, symbol, data):
    lines = [
        "// GENERATED by tools/gen_setup_page.py from lib/network/web/%s. Do not edit:" % page,
        "// edit %s and run  python tools/gen_setup_page.py" % page,
        MARK + digest(data),
        '#include "brew/network/setup_portal.h"',
        "",
        "namespace brew::net {",
        "",
        "const char %s[] = {" % symbol,
    ]
    for i in range(0, len(data), 16):
        # character literals, not ints: bytes above 0x7F would be narrowing conversions into char
        lines.append("    " + ", ".join("'\\x%02x'" % b for b in data[i:i + 16]) + ",")
    lines += [
        "    '\\0'",
        "};",
        "const size_t %sLen = %d;" % (symbol, len(data)),
        "",
        "}  // namespace brew::net",
        "",
    ]
    return "\n".join(lines)


def stale():
    """Generated files that don't match their page (missing ones included)."""
    out = []
    for page, gen, _ in PAGES:
        path = os.path.join(SRC_DIR, gen)
        ok = False
        if os.path.exists(path) and os.path.exists(os.path.join(WEB, page)):
            want = digest(read_src(page))
            with open(path, encoding="utf-8") as f:
                for line in f:
                    if line.startswith(MARK):
                        ok = line[len(MARK):].strip() == want
                        break
        if not ok:
            out.append("lib/network/src/" + gen)
    return out


def is_current():
    return not stale()


def main():
    if "--check" in sys.argv:
        bad = stale()
        if not bad:
            return 0
        print("out of date: %s: run  python tools/gen_setup_page.py" % ", ".join(bad))
        return 1
    for page, gen, symbol in PAGES:
        data = read_src(page)
        with open(os.path.join(SRC_DIR, gen), "w", encoding="utf-8", newline="\n") as f:
            f.write(render(page, symbol, data))
        print("wrote lib/network/src/%s (%d bytes of page)" % (gen, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
