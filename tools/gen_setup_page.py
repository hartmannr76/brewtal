#!/usr/bin/env python3
"""
Embeds the WiFi setup page into the firmware:

    lib/network/web/setup.html  ->  lib/network/src/setup_page.cpp   (kSetupPage, kSetupPageLen)

    python tools/gen_setup_page.py           regenerate
    python tools/gen_setup_page.py --check   exit 1 if setup_page.cpp is out of date
                                             (tools/check_rules.py runs this on every build)

The generated file records the page's SHA-256, so a stale copy is caught without comparing bytes.
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "lib", "network", "web", "setup.html")
OUT = os.path.join(ROOT, "lib", "network", "src", "setup_page.cpp")
MARK = "// source sha256: "


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read_src():
    """The page with LF line endings, whatever the checkout uses (Windows may give CRLF)."""
    with open(SRC, "rb") as f:
        return f.read().replace(b"\r\n", b"\n")


def render(data):
    lines = [
        "// GENERATED by tools/gen_setup_page.py from lib/network/web/setup.html. Do not edit:",
        "// edit setup.html and run  python tools/gen_setup_page.py",
        MARK + digest(data),
        '#include "brew/network/setup_portal.h"',
        "",
        "namespace brew::net {",
        "",
        "const char kSetupPage[] = {",
    ]
    for i in range(0, len(data), 16):
        # character literals, not ints: bytes above 0x7F would be narrowing conversions into char
        lines.append("    " + ", ".join("'\\x%02x'" % b for b in data[i:i + 16]) + ",")
    lines += [
        "    '\\0'",
        "};",
        "const size_t kSetupPageLen = %d;" % len(data),
        "",
        "}  // namespace brew::net",
        "",
    ]
    return "\n".join(lines)


def is_current():
    """True if setup_page.cpp was generated from the current setup.html."""
    if not os.path.exists(SRC) or not os.path.exists(OUT):
        return False
    want = digest(read_src())
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            if line.startswith(MARK):
                return line[len(MARK):].strip() == want
    return False


def main():
    if "--check" in sys.argv:
        if is_current():
            return 0
        print("lib/network/src/setup_page.cpp is out of date: run  python tools/gen_setup_page.py")
        return 1
    data = read_src()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(data))
    print("wrote %s (%d bytes of page)" % (os.path.relpath(OUT, ROOT), len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
